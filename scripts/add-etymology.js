// Read the file
const filePath = resolve('/vercel/share/v0-project/lib/words-hard.ts')
const content = readFileSync(filePath, 'utf-8')

// For each word entry, add etymology after synonyms line
let modified = content
let addedCount = 0

// Match each word entry and inject etymology
for (const [word, etym] of Object.entries(etymologies)) {
  // Find the synonyms line for this word and add etymology after it
  // We look for the pattern: word: "word", ... synonyms: [...],
  const escapedWord = word.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&')
  const regex = new RegExp(
    `(word: "${escapedWord}",\\n(?:.*\\n)*?\\s+synonyms: \\[[^\\]]*\\],)`,
    'm'
  )
  const match = modified.match(regex)
  if (match) {
    const existing = match[1]
    // Only add if etymology not already present
    if (!existing.includes('etymology:') && !modified.includes(`word: "${word}",\n`) || true) {
      const replacement = existing + `\n    etymology: "${etym.replace(/"/g, '\\"')}",`
      modified = modified.replace(existing, replacement)
      addedCount++
    }
  }
}

writeFileSync(filePath, modified, 'utf-8')
